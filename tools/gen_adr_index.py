"""Generate an index page for a directory of MADR decision records.

Reads every ``NNNN-*.md`` record in the given directory, extracts the title,
front-matter ``status`` and ``date``, and the cross-references between
records, and writes an ``index.md`` containing a status table and a Mermaid
relationship graph. The output is deterministic: running the tool twice over
unchanged records produces byte-identical output, so ``--check`` can gate CI.

The records are the source of truth; the index is generated and should not be
edited by hand. See README.md next to this script for usage.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

RECORD_PATTERN = re.compile(r"^\d{4}-[a-z0-9-]+\.md$")
LINK_PATTERN = re.compile(r"\]\((\d{4}-[a-z0-9-]+\.md)(?:#[^)]*)?\)")
TITLE_PATTERN = re.compile(r"^# (.+)$", re.MULTILINE)
MERMAID_LABEL_LIMIT = 44

GENERATED_MARKER = "<!-- Generated by gen_adr_index.py; edit the records, not this file. -->"

SPDX_HEADER = """<!--
SPDX-FileCopyrightText: 2026 Tazlin

SPDX-License-Identifier: AGPL-3.0-or-later
-->"""


@dataclass
class Record:
    """One decision record as read from disk."""

    filename: str
    title: str
    status: str
    date: str
    references: list[str] = field(default_factory=list)

    @property
    def number(self) -> str:
        return self.filename[:4]


def parse_front_matter(text: str) -> dict[str, str]:
    """Extract simple ``key: value`` pairs from a leading YAML front-matter block."""
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    fields: dict[str, str] = {}
    for line in text[4:end].splitlines():
        stripped = line.strip()
        if stripped.startswith("#") or ":" not in stripped:
            continue
        key, _, value = stripped.partition(":")
        fields[key.strip()] = value.strip().strip("\"'")
    return fields


def read_record(path: Path) -> Record:
    text = path.read_text(encoding="utf-8")
    front_matter = parse_front_matter(text)
    title_match = TITLE_PATTERN.search(text)
    title = title_match.group(1).strip() if title_match else path.stem
    references = sorted(
        {target for target in LINK_PATTERN.findall(text) if target != path.name},
    )
    return Record(
        filename=path.name,
        title=title,
        status=front_matter.get("status", "unknown"),
        date=front_matter.get("date", "unknown"),
        references=references,
    )


def mermaid_label(record: Record) -> str:
    label = f"{record.number}: {record.title}"
    if len(label) > MERMAID_LABEL_LIMIT:
        label = label[: MERMAID_LABEL_LIMIT - 1].rstrip() + "…"
    return label.replace('"', "'")


def render_index(records: list[Record]) -> str:
    lines: list[str] = [
        SPDX_HEADER,
        "",
        GENERATED_MARKER,
        "",
        "# Decisions",
        "",
        "One decision per record: what was chosen, what was rejected, and what it cost.",
        "",
        "| Record | Status | Date |",
        "| --- | --- | --- |",
    ]
    for record in records:
        lines.append(f"| [{record.title}]({record.filename}) | {record.status} | {record.date} |")

    edges = [
        (record, target)
        for record in records
        for target in record.references
        if any(other.filename == target for other in records)
    ]
    if edges:
        lines += [
            "",
            "## Relationships",
            "",
            "An edge points from a record to a record it references.",
            "",
            "```mermaid",
            "flowchart TD",
        ]
        for record in records:
            lines.append(f'    r{record.number}["{mermaid_label(record)}"]')
        for record, target in edges:
            lines.append(f"    r{record.number} --> r{target[:4]}")
        lines += ["```"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("decisions_dir", type=Path, help="Directory containing NNNN-*.md records")
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Output path (default: index.md inside the decisions directory)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the output file is missing or out of date instead of writing",
    )
    args = parser.parse_args(argv)

    record_paths = sorted(
        path for path in args.decisions_dir.iterdir() if RECORD_PATTERN.match(path.name)
    )
    if not record_paths:
        print(f"No NNNN-*.md records found in {args.decisions_dir}", file=sys.stderr)
        return 1

    output_path = args.output or args.decisions_dir / "index.md"
    rendered = render_index([read_record(path) for path in record_paths])

    if args.check:
        current = output_path.read_text(encoding="utf-8") if output_path.exists() else None
        if current != rendered:
            print(f"{output_path} is out of date; regenerate with gen_adr_index.py", file=sys.stderr)
            return 1
        return 0

    output_path.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {output_path} ({len(record_paths)} records)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
